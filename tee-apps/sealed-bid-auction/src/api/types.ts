export interface PreauctionRequest {
    id: string; // must be a UUID V4 generated by frontend
    srcChainId: number;
    dstChainId: number;
    srcTokenAddress: string;
    dstTokenAddress: string;
    amountIn: string; // must be an integer representing the smallest denomination of the token
}

export interface PreauctionQuote {
    id: string;
    request: {
        srcChainId: number;
        dstChainId: number;
        srcTokenAddress: string;
        dstTokenAddress: string;
        amountIn: number;
    },
    amountOut: string;
    solverAddress: string;
    timestamp: number;
}
